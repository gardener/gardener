set -e
set -o pipefail

source "$(dirname "$0")/../../../hack/lockfile.sh"
acquire_lockfile "/tmp/generate-patch-gardenlet.sh.lock"

dir="$(dirname $0)"
type="${1:-image}"
ref="$SKAFFOLD_IMAGE"

if [[ "$type" == "helm" ]]; then
  patch_file="$dir/patch-helm-ref.yaml"
  cat <<EOF > "$patch_file"
apiVersion: seedmanagement.gardener.cloud/v1alpha1
kind: Gardenlet
metadata:
  name: local
  namespace: garden
spec:
  deployment:
    helm:
      ociRepository:
        ref: $ref
EOF
  # The local dev registry uses a self-signed CA (generated by infra.sh), so the gardenlet must be told to
  # trust it via caBundleSecretRef when pulling its Helm chart. The remote seed registry uses a
  # cert-management-issued, publicly-trusted certificate instead, so no bundle is needed there - and pointing
  # at the local CA would be wrong, since the OCI puller (pkg/utils/oci/helmregistry.go) builds a fresh cert
  # pool from the bundle alone and thereby replaces the system trust store. Skip it for the remote scenario.
  if [[ "$SCENARIO" != "remote" ]]; then
    cat <<EOF >> "$patch_file"
        caBundleSecretRef:
          name: gardener-local-registry-ca
EOF
  fi
fi

if [[ "$type" == "image" ]]; then
  image_name="$2"
  repository="$(echo "$ref" | rev | cut -d':' -f 2- | rev)"
  tag="$(echo "$ref" | rev | cut -d':' -f 1 | rev)"

  patch_file="$dir/patch-imagevector-overwrite.yaml"
  if [[ ! -f "$patch_file" ]]; then
    cat <<EOF > "$patch_file"
apiVersion: seedmanagement.gardener.cloud/v1alpha1
kind: Gardenlet
metadata:
  name: local
  namespace: garden
spec:
  deployment:
    imageVectorOverwrite: |
      images: []
EOF
  fi

  images="$(yq e '.spec.deployment.imageVectorOverwrite' "$patch_file" | yq -o json)"

  images="$(echo "$images" | jq -r \
    --arg name "$image_name" \
    --arg repository "$repository" \
    --arg tag "$tag" \
    '.images |= if any(.name == $name) then
        map(if .name == $name then .repository = $repository | .tag = $tag else . end)
      else
        . + [{name: $name, repository: $repository, tag: $tag}] end' |\
   yq eval -P)"

  # Trust the local registry's self-signed CA (generated by infra.sh) so gardener-node-agent can pull
  # bootstrap images from the HTTPS registry on shoot worker nodes. The remote seed registry uses a
  # publicly-trusted cert, so no bundle is needed there - skip it for the remote scenario.
  ca_crt="$dir/../../infra/registry/tls/ca.crt"
  if [[ "$SCENARIO" != "remote" && -f "$ca_crt" ]]; then
    images="$(CA="$(cat "$ca_crt")" yq eval '.caBundle.inline = strenv(CA)' - <<<"$images")"
  else
    # Remote seed registry uses a publicly-trusted cert - drop any caBundle left over from a previous local run.
    images="$(yq eval 'del(.caBundle)' - <<<"$images")"
  fi

  IMAGES="$images" yq eval '.spec.deployment.imageVectorOverwrite = strenv(IMAGES)' -i "$patch_file"
fi
